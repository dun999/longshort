// Copies contract ABIs from forge's out/ into the shared package as typed TS consts.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const pick = (file, name) =>
  JSON.parse(readFileSync(join(root, 'contracts/out', file, `${name}.json`), 'utf8')).abi;

const abis = {
  arenaAbi: pick('ArenaCore.sol', 'ArenaCore'),
  erc20Abi: pick('TestUSD.sol', 'TestUSD'),
  mockOracleAbi: pick('MockOracle.sol', 'MockOracle'),
  priceOracleAbi: pick('IPriceOracle.sol', 'IPriceOracle'),
};
const body = Object.entries(abis)
  .map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)} as const;`)
  .join('\n\n');
writeFileSync(join(root, 'packages/shared/src/abis.ts'), `// generated by scripts/export-abi.mjs — do not edit\n${body}\n`);
console.log('wrote packages/shared/src/abis.ts');
