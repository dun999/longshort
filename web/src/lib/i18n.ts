const dict: Record<Lang, Record<Key, string>> = { en, id };

export const useLang = create<{ lang: Lang; set: (l: Lang) => void }>((set) => ({
  lang: 'en',
  set: (lang) => {
    try {
      localStorage.setItem('ls.lang', lang);
    } catch {}
    if (typeof document !== 'undefined') document.documentElement.lang = lang;
    set({ lang });
  },
}));

/** After hydration: saved choice, else the browser's language. */
export function initLang() {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem('ls.lang');
  } catch {}
  const lang: Lang = saved === 'id' || saved === 'en' ? saved : navigator.language?.toLowerCase().startsWith('id') ? 'id' : 'en';
  if (lang !== useLang.getState().lang) useLang.getState().set(lang);
}

type Vars = Record<string, string | number>;
const fill = (s: string, v?: Vars) => (v ? s.replace(/\{(\w+)\}/g, (_, k) => String(v[k] ?? '')) : s);

/** Outside React (errors, toasts). */
export const tr = (key: Key, v?: Vars) => fill(dict[useLang.getState().lang][key] ?? en[key], v);

export function useT() {
  const lang = useLang((s) => s.lang);
  return useCallback((key: Key, v?: Vars) => fill(dict[lang][key] ?? en[key], v), [lang]);
}
